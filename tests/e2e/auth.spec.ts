test('corações dos cards: contraste, hover, foco, autenticação, pending e rollback', async ({ page }, testInfo) => {
  if (page.viewportSize()!.width <= 600) await page.setViewportSize({ width: 414, height: 896 })
  const card = page.getByTestId(`nft-${nftId}`)
  const button = favorite(page)
  async function visualState() {
    const state = await button.evaluate(element => {
      const svg = element.querySelector('svg')!, rect = svg.getBoundingClientRect(), style = getComputedStyle(element), graphic = getComputedStyle(svg)
      return { width: rect.width, height: rect.height, opacity: style.opacity, background: style.backgroundColor, stroke: graphic.stroke, fill: graphic.fill, shrink: graphic.flexShrink }
    })
    expect(state.width).toBe(20)
    expect(state.height).toBe(20)
    expect(state.shrink).toBe('0')
    expect(state.opacity).toBe('1')
    const luminance = (color: string) => color.match(/[\d.]+/g)!.slice(0, 3).map(Number).map(value => value / 255).map(value => value <= .04045 ? value / 12.92 : ((value + .055) / 1.055) ** 2.4).reduce((sum, value, index) => sum + value * [0.2126, 0.7152, 0.0722][index]!, 0)
    const foreground = luminance(state.stroke), background = luminance(state.background)
    expect((Math.max(foreground, background) + .05) / (Math.min(foreground, background) + .05)).toBeGreaterThanOrEqual(3)
    return state
  }
  await expect(button).toBeEnabled()
  await expect(button).toHaveAccessibleName('Favoritar Emerald Ape #042')
  const inactive = await visualState()
  expect(inactive.fill).toBe('none')
  await button.hover()
  const hovered = await visualState()
  await card.getByRole('link').focus()
  await page.keyboard.press('Tab')
  await expect(button).toBeFocused()
  await expect(button).toHaveCSS('outline-style', 'solid')
  await expect(button).toHaveCSS('outline-width', '2px')
  await page.keyboard.press('Space')
  await expect(page.getByRole('dialog')).toBeVisible()
  await login(page, 'ana')
  await expect(button).toBeEnabled()
  await control(page, 'auth/scenario', { mutationDelay: 650 })
  const added = favoriteResponse(page)
  await button.focus()
  await page.keyboard.press('Space')
  await expect(button).toHaveAttribute('aria-busy', 'true')
  await expect(button).toBeDisabled()
  const pending = await visualState()
  expect((await added).status()).toBe(200)
  await expect(button).toBeEnabled()
  await expect(button).toHaveAttribute('aria-pressed', 'true')
  await expect(button).toHaveAccessibleName('Desfavoritar Emerald Ape #042')
  const active = await visualState()
  expect(active.fill).toBe(active.stroke)
  await control(page, 'auth/scenario', { favoritesFailure: true, mutationDelay: 650 })
  const refused = favoriteResponse(page)
  await button.click()
  await expect(button).toHaveAttribute('aria-pressed', 'false')
  expect((await refused).status()).toBe(503)
  await expect(button).toHaveAttribute('aria-pressed', 'true')
  const error = card.getByRole('alert')
  await error.scrollIntoViewIfNeeded()
  await expect(error).toBeInViewport()
  await control(page, 'auth/scenario', { favoritesFailure: false, mutationDelay: 120 })
  const removed = favoriteResponse(page)
  await button.click()
  expect((await removed).status()).toBe(200)
  await expect(button).toHaveAttribute('aria-pressed', 'false')
  expect((await visualState()).fill).toBe('none')
  await testInfo.attach('estados-visuais-do-favorito', { body: JSON.stringify({ inactive, hovered, pending, active }), contentType: 'application/json' })
})

