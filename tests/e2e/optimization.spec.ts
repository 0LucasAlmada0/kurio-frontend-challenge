import { test, expect } from '@playwright/test'
import { openCheckoutReview } from './checkout-ui'

test('produção: MSW antes das consultas, imagens sem perda, metadados e refresh interno', async ({ page, request }) => {
  const apiResponses: boolean[] = []
  const errors: string[] = []
  page.on('response', (response) => { if (new URL(response.url()).pathname.startsWith('/api/')) apiResponses.push(response.fromServiceWorker()) })
  page.on('pageerror', (error) => errors.push(error.message))
  page.on('console', (message) => { if (message.type() === 'error') errors.push(message.text()) })
  await page.goto('/')
  await expect(page.getByTestId('socket-status')).toHaveText('● Ao vivo')
  await expect(page.getByRole('article')).toHaveCount(8)
  const image = page.getByTestId('nft-emerald-ape-042').getByRole('img')
  await expect.poll(() => image.evaluate((img: HTMLImageElement) => img.complete && img.naturalWidth === 500 && img.currentSrc.endsWith('/emerald-ape.webp'))).toBe(true)
  await expect(page).toHaveTitle('Kurio — Cultura digital')
  expect(await page.locator('meta[name="description"]').getAttribute('content')).toContain('coleções')
  const robots = await request.get('/robots.txt')
  expect(robots.status()).toBe(200)
  expect(await robots.text()).toBe('User-agent: *\nAllow: /\n')
  const favicon = await request.get('/favicon.png')
  expect(favicon.status()).toBe(200)
  expect(favicon.headers()['content-type']).toContain('image/png')
  await page.goto('/nfts/emerald-ape-042')
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Emerald Ape #042')
  await expect(page).toHaveTitle('Emerald Ape #042 | Kurio')
  await expect.poll(() => page.locator('.detail-art > img').evaluate((img: HTMLImageElement) => img.complete && img.currentSrc.endsWith('/emerald-ape.webp'))).toBe(true)
  await page.reload()
  await expect(page.getByTestId('detail-emerald-ape-042').getByTestId('price')).toHaveText('1.19 ETH')
  await expect(page.getByTestId('socket-status')).toHaveText('● Ao vivo')
  expect(apiResponses.length).toBeGreaterThan(3)
  expect(apiResponses.every(Boolean)).toBe(true)
  expect(errors).toEqual([])
})

test('rotas carregadas sob demanda preservam autenticação, carteiras, carrinho e pagamento', async ({ page }) => {
  await page.goto('/perfil')
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('E-mail', { exact: true }).fill('ana@kurio.test')
  await dialog.getByLabel('Senha', { exact: true }).fill('KurioDemo!123')
  await dialog.getByRole('button', { name: 'Entrar', exact: true }).click()
  await expect(page).toHaveURL(/\/perfil$/)
  await expect(page.getByLabel('Nome de exibição', { exact: false })).toHaveValue('Ana')
  await page.reload()
  await expect(page.getByLabel('Nome de exibição', { exact: false })).toHaveValue('Ana')
  await page.goto('/carteiras')
  await expect(page.getByRole('form', { name: 'Editar carteira Principal', exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('form', { name: 'Editar carteira Principal', exact: true })).toBeVisible()
  expect(await page.evaluate(async () => (await fetch('/api/cart/items', { method: 'PUT', headers: { 'Content-Type': 'application/json', Authorization: `Bearer ${localStorage.getItem('kurio:session-token')}` }, body: JSON.stringify({ nftId: 'emerald-ape-042', editionId: 'standard', quantity: 1, operation: 'add' }) })).status)).toBe(200)
  await page.goto('/pagamento')
  await expect(page.getByRole('heading', { name: 'Pagamento com carteira', exact: true })).toBeVisible()
  await openCheckoutReview(page)
  await expect(page.getByRole('textbox', { name: 'Nome de exibição', exact: true })).toHaveValue('Ana')
  await page.reload()
  await openCheckoutReview(page)
  await expect(page.getByRole('textbox', { name: 'Nome de exibição', exact: true })).toHaveValue('Ana')
  await page.goto('/carrinho')
  await expect(page.getByTestId('cart-emerald-ape-042-standard')).toBeVisible()
  await page.reload()
  await expect(page.getByTestId('cart-emerald-ape-042-standard')).toBeVisible()
  await page.goto('/favoritos')
  await expect(page.getByText('Você ainda não tem favoritos.', { exact: true })).toBeVisible()
})

test('painéis sob demanda preservam edição local e todos os controles de demonstração', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByTestId('socket-status')).toHaveText('● Ao vivo')
  const card = page.getByTestId('nft-emerald-ape-042')
  await card.locator('summary').click()
  await card.getByRole('spinbutton').fill('2')
  await card.locator('summary').click()
  await card.locator('summary').click()
  await expect(card.getByRole('spinbutton')).toHaveValue('2')
  const controls = page.locator('.mock-controls')
  await controls.locator('summary').click()
  await controls.getByRole('button', { name: 'Alterar Emerald Ape', exact: true }).click()
  await expect(card.getByTestId('price')).toHaveText('1.49 ETH')
  await expect(card.getByRole('spinbutton')).toHaveValue('2')
  await controls.getByLabel('Resposta da API').selectOption('variable')
  await expect(controls.getByLabel('Resposta da API')).toBeEnabled()
  await controls.locator('summary').click()
  await controls.locator('summary').click()
  await expect(controls.getByLabel('Resposta da API')).toHaveValue('variable')
  await controls.getByRole('button', { name: 'Restaurar cenário', exact: true }).click()
  await expect(card.getByTestId('price')).toHaveText('1.19 ETH')
  await expect(page.getByTestId('socket-status')).toHaveText('● Ao vivo')
})
