import { expect, test, type Page } from '@playwright/test'
import type { Nft } from '../../src/api/contracts'

const nftId = 'emerald-ape-042'
async function control(page: Page, path: string, body: unknown) {
  return page.evaluate(async ({ path, body }) => {
    const response = await fetch(`/api/__mock/${path}`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(body) })
    if (!response.ok) throw new Error(`Mock control failed: ${response.status}`)
  }, { path, body })
}

test.beforeEach(async ({ page }) => {
  await page.clock.install({ time: new Date('2026-10-21T12:01:00Z') })
  await page.goto('/')
  await expect(page.getByTestId('socket-status')).toHaveText('● Ao vivo')
  await control(page, 'reset', {})
  await page.goto(`/nfts/${nftId}`)
  await expect(page.getByTestId(`detail-${nftId}`)).toBeVisible()
})

test('detalhe: composição mobile, metadados REST, toque e foco sem sobreposição', async ({ page }) => {
  const nft = await page.evaluate(async () => (await fetch('/api/nfts/emerald-ape-042')).json() as Promise<Nft>)
  const detail = page.getByTestId(`detail-${nftId}`)
  await expect(detail.getByRole('heading', { level: 1 })).toHaveText(nft.name)
  await expect(detail.locator('.detail-about p')).toHaveText(nft.description)
  await expect(detail.locator('.detail-meta')).toContainText(nft.id)
  await expect(detail.locator('.detail-meta')).toContainText(nft.collection)
  await expect(detail.locator('.detail-meta')).toContainText(nft.rarity)
  await expect(detail.locator('.edition-options button')).toHaveCount(nft.editions.length)
  const initial = page.viewportSize()!
  for (const size of initial.width <= 600 ? [{ width: 414, height: 896 }, { width: 390, height: 844 }, { width: 390, height: 500 }] : [initial]) {
    await page.evaluate(() => { (document.activeElement as HTMLElement)?.blur() })
    await page.setViewportSize(size)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    if (size.width <= 600) {
      await page.evaluate(() => window.scrollTo({ top: 0, behavior: 'instant' }))
      const favorite = detail.locator('.gallery-toolbar .favorite-button')
      await expect(favorite).toBeEnabled()
      await favorite.scrollIntoViewIfNeeded()
      const icon = (await favorite.locator('svg').boundingBox())!
      expect(icon.width).toBeGreaterThanOrEqual(20)
      expect(icon.height).toBeGreaterThanOrEqual(20)
      const button = (await favorite.boundingBox())!
      expect(await page.evaluate(({ x, y }) => document.elementFromPoint(x, y)?.closest('button')?.classList.contains('favorite-button'), { x: button.x - 4, y: button.y + button.height / 2 })).toBe(true)
      const quantity = (await detail.locator('.quantity-control').boundingBox())!
      const price = (await detail.getByTestId('price').boundingBox())!
      expect(quantity.x + quantity.width).toBeLessThanOrEqual(price.x)
      await expect(detail.locator('.detail-copy')).toHaveCSS('font-family', /Roboto Mono/)
      await expect(detail.locator('.detail-purchase')).not.toHaveCSS('position', /fixed|sticky/)
      const add = detail.getByRole('button', { name: 'Adicionar ao carrinho', exact: true })
      expect((await add.boundingBox())!.height).toBeGreaterThanOrEqual(44)
      await add.focus()
      await expect(add).toBeFocused()
      await expect(add).toBeInViewport({ ratio: 1 })
      await page.keyboard.press('Tab')
      await expect(detail.locator('.mobile-cart')).toBeFocused()
      await expect(detail.locator('.mobile-cart')).toBeInViewport({ ratio: 1 })
    }
  }
  await expect(page.getByRole('heading', { name: 'Detalhes do NFT', exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Mais desta coleção', exact: true })).toBeVisible()
  await expect(page.getByText('Cenários de demonstração', { exact: true })).toBeVisible()
})

test('detalhe: favorito visível ativo/inativo, autenticação e rollback', async ({ page }) => {
  const detail = page.getByTestId(`detail-${nftId}`)
  const favorite = detail.getByRole('button', { name: /favoritar Emerald Ape #042$/i }).filter({ visible: true })
  await expect(favorite).toHaveAttribute('aria-pressed', 'false')
  await favorite.click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('E-mail', { exact: true }).fill('ana@kurio.test')
  await dialog.getByLabel('Senha', { exact: true }).fill('KurioDemo!123')
  await dialog.getByRole('button', { name: 'Entrar', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await expect(favorite).toBeEnabled()
  await favorite.focus()
  const added = page.waitForResponse(response => response.url().endsWith(`/favorites/${nftId}`) && response.request().method() === 'PUT')
  await page.keyboard.press('Space')
  expect((await added).status()).toBe(200)
  await expect(favorite).toHaveAttribute('aria-pressed', 'true')
  await expect(favorite).toBeEnabled()
  const activeStyle = await favorite.locator('svg').evaluate(element => ({ fill: getComputedStyle(element).fill, color: getComputedStyle(element).color, width: element.getBoundingClientRect().width }))
  expect(activeStyle.fill).toBe(activeStyle.color)
  expect(activeStyle.width).toBeGreaterThanOrEqual(18)
  await control(page, 'auth/scenario', { favoritesFailure: true, mutationDelay: 500 })
  const refused = page.waitForResponse(response => response.url().endsWith(`/favorites/${nftId}`) && response.request().method() === 'DELETE')
  await favorite.click()
  await expect(favorite).toHaveAttribute('aria-pressed', 'false')
  expect((await refused).status()).toBe(503)
  await expect(favorite).toHaveAttribute('aria-pressed', 'true')
  await expect(detail.getByRole('alert')).toBeInViewport()
  await control(page, 'auth/scenario', { favoritesFailure: false, mutationDelay: 120 })
  const removed = page.waitForResponse(response => response.url().endsWith(`/favorites/${nftId}`) && response.request().method() === 'DELETE')
  await favorite.click()
  expect((await removed).status()).toBe(200)
  await expect(favorite).toHaveAttribute('aria-pressed', 'false')
  await expect(favorite.locator('svg')).toHaveCSS('fill', 'none')
})

test('detalhe: edições, quantidade, ETH preciso, falha e acesso ao carrinho', async ({ page }) => {
  const detail = page.getByTestId(`detail-${nftId}`)
  const add = detail.getByRole('button', { name: 'Adicionar ao carrinho', exact: true })
  const quantity = detail.getByRole('spinbutton')
  const limited = detail.getByRole('button', { name: /^Edição 1\/10 de / })
  await limited.focus()
  await page.keyboard.press('Space')
  await expect(limited).toHaveAttribute('aria-pressed', 'true')
  await expect(detail.getByRole('button', { name: /^Aumentar quantidade/ })).toBeDisabled()
  await quantity.fill('2')
  await expect(add).toBeDisabled()
  await control(page, `nfts/${nftId}/update`, { editionId: 'limited', available: 0, priceEth: '1.123456789012345678' })
  await expect(detail.getByTestId('price')).toHaveText('1.123456789012345678 ETH')
  await expect(detail.getByRole('status').filter({ hasText: 'Edição esgotada.' })).toBeVisible()
  await expect(quantity).toBeDisabled()
  await expect(add).toBeDisabled()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await detail.getByRole('button', { name: /^Edição 1\/50 de / }).click()
  await expect(quantity).toHaveValue('1')
  await detail.getByRole('button', { name: /^Aumentar quantidade/ }).click()
  await expect(quantity).toHaveValue('2')
  await control(page, 'cart/scenario', { failure: 'server' })
  await add.click()
  const error = detail.getByRole('alert')
  await expect(error).toBeVisible()
  await error.scrollIntoViewIfNeeded()
  await expect(error).toBeInViewport()
  await control(page, 'cart/scenario', { failure: 'none' })
  const added = page.waitForResponse(response => response.url().endsWith('/api/cart/items') && response.request().method() === 'PUT')
  await add.click()
  expect((await added).status()).toBe(200)
  await expect(detail.getByRole('status').filter({ hasText: 'Adicionado.' })).toBeVisible()
  await detail.getByRole('link', { name: 'Ver carrinho', exact: true }).click()
  await expect(page.getByTestId(`cart-${nftId}-standard`).getByRole('spinbutton')).toHaveValue('2')
})
